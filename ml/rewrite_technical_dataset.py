def map_employee(name: str, login: str):
    key = (login or "").strip().lower()
    if key in EMPLOYEES:
        return EMPLOYEES[key]
    return name, login


def main():
    with open(DATA_PATH, encoding="utf-8") as f:
        data = json.load(f)

    base_records = [r for r in data if not r["id"].startswith("INC00002190")]
    for idx, rec in enumerate(base_records):
        grp = rec.get("assignedGroupName", "")
        prof = GROUP_TECH_PROFILES.get(grp)
        if prof:
            prod, prod_id, svc, scen, hdr, desc, sol = prof
            variant_prefix = ""
            if idx % 3 == 1 and rec.get("priorityId", 2) >= 3:
                variant_prefix = "Повторный инцидент: "
            elif idx % 4 == 2:
                variant_prefix = "Алерт мониторинга: "

            rec["productName"] = prod
            rec["productMasterId"] = prod_id
            rec["service"] = svc
            rec["scenarioName"] = scen
            rec["header"] = variant_prefix + hdr
            rec["shortDescription"] = hdr
            rec["description"] = desc
            rec["solution"] = sol

        if grp == "КЦ ИТ Координаторы Массовых Инцидентов":
            if idx % 2 == 0:
                rec["productName"] = "Платформа виртуализации InfraCloud"
                rec["service"] = "[InfraCloud] Кластер гипервизоров VMWare ESXi"
                rec["scenarioName"] = "Гипервизор ESXi"
                rec["header"] = "Деградация гипервизоров VMWare ESXi и ошибки vMotion"
                rec["shortDescription"] = rec["header"]
                rec["description"] = "В кластере виртуализации VMWare ESXi зафиксирован рост CPU Ready и сбои миграции виртуальных машин. Заявка ошибочно назначена на координаторов."
            else:
                rec["productName"] = "Корпоративный удаленный доступ VPN"
                rec["service"] = "[VPN] Шлюз удаленного доступа IPsec/WireGuard"
                rec["scenarioName"] = "Туннель VPN"
                rec["header"] = "Массовые обрывы VPN-сессий при подключении сотрудников"
                rec["shortDescription"] = rec["header"]
                rec["description"] = "Удаленные пользователи получают ошибку рукопожатия TLS на шлюзе VPN. Требуется передача профильной команде поддержки VPN."

        emp_name, emp_login = map_employee(rec.get("assignedEmployee", ""), rec.get("assignedEmployeeLogin", ""))
        rec["assignedEmployee"] = emp_name
        rec["assignedEmployeeLogin"] = emp_login

        init_name, init_login = map_employee(rec.get("initiatorName", ""), rec.get("initiatorLogin", ""))
        rec["initiatorName"] = init_name
        rec["initiatorLogin"] = init_login

        ch = rec.get("receivingChannel", "")
        if ch in CHANNELS:
            rec["receivingChannel"] = CHANNELS[ch]

    with open(DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(base_records, f, ensure_ascii=False, indent=2)

    print(f"Rewrote {len(base_records)} base records to clean technical IT terminology.")


if __name__ == "__main__":
    main()
